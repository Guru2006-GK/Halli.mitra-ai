export const HISTORICAL_DEMAND_RECORDS: HistoricalDemandRecord[] = (() => {
  const corridors = [
    { id: 'corridor_malavalli_mandya', name: 'Malavalli – Kirugavalu – PES Mandya', base: 112, growth: 0.9 },
    { id: 'corridor_halaguru_mandya', name: 'Halaguru – Malavalli – PES Mandya', base: 86, growth: 0.7 },
    { id: 'corridor_koppa_maddur', name: 'Koppa – Maddur – GFGC Maddur', base: 94, growth: 0.6 },
    { id: 'corridor_bannur_mysuru', name: 'Bannur – Srirangapatna – Mysuru', base: 88, growth: 0.8 },
    { id: 'corridor_pandavapura_mandya', name: 'Pandavapura – Srirangapatna – Mandya', base: 78, growth: 0.5 },
  ];
  const dayNames = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  const records: HistoricalDemandRecord[] = [];
  const start = new Date('2026-10-14T00:00:00Z');
  for (let day = 0; day < 28; day++) {
    const dt = new Date(start.getTime() + day * 86400000);
    const dow = dt.getUTCDay();
    const isWeekend = dow === 0 || dow === 6;
    const isExamPeriod = day >= 16 && day <= 21;
    const isHoliday = day === 12;
    const iso = dt.toISOString().slice(0, 10);
    for (const c of corridors) {
      let val = c.base + day * c.growth;
      if (dow === 1 || dow === 2) val *= 1.09; // Mon/Tue peak attendance
      if (dow === 6) val *= 0.62;
      if (dow === 0) val *= 0.16;
      if (isExamPeriod && !isWeekend) val *= 1.24;
      if (isHoliday) val *= 0.18;
      // deterministic ripple
      val += ((day * 7 + c.base) % 9) - 4;
      records.push({
        date: iso,
        dayOfWeek: dayNames[dow],
        isWeekend,
        isExamPeriod,
        isHoliday,
        corridorId: c.id,
        corridorName: c.name,
        actualStudents: Math.max(8, Math.round(val)),
      });
    }
  }
  return records;
})();
